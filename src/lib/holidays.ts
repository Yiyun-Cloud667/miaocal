/** 查询某日的节日名（无则 undefined）。dateStr: YYYY-MM-DD */
export function holidayOf(dateStr: string): string | undefined {
  const year = Number(dateStr.slice(0, 4))
  const lunar = LUNAR_TABLE[year]?.[dateStr]
  if (lunar) return lunar
  return SOLAR[dateStr.slice(5)]
}

/** 法定/传统节日（用于月历红字高亮） */
const MAJOR = new Set([
  '元旦', '除夕', '春节', '元宵节', '清明节', '劳动节',
  '端午节', '中秋节', '国庆节', '腊八节',
])

export function isMajorHoliday(name: string | undefined): boolean {
  return !!name && MAJOR.has(name)
}
